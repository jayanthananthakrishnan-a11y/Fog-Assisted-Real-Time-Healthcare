function Invoke-Simulation(
    [string]$arch,
    [int]$numPatients = 10,
    [int]$windowSize = 5,
    [double]$wanLatency = 100.0,
    [double]$wanBw = 10000.0
) {
    $mainClass = switch ($arch.ToUpper()) {
        "A" { "baseline.HealthcareCloudOnly" }
        "B" { "fog_forwarding.HealthcareFogForwarding" }
        "C" { "fog_filtering.HealthcareFogFiltering" }
        "D" { "priority_aware.HealthcarePriorityFog" }
        Default { throw "Unknown Architecture: $arch" }
    }

    $summaryFile = switch ($arch.ToUpper()) {
        "A" { "results/csv/arch_a_baseline_summary.csv" }
        "B" { "results/csv/arch_b_forwarding_summary.csv" }
        "C" { "results/csv/arch_c_filtering_summary.csv" }
        "D" { "results/csv/arch_d_priority_summary.csv" }
    }

    # Delete previous summary file to guarantee fresh read
    if (Test-Path $summaryFile) {
        Remove-Item -Force $summaryFile
    }

    # Run Java simulation process in isolated JVM
    & java -cp $runClasspath $mainClass $numPatients $windowSize $wanLatency $wanBw | Out-Null
    if ($LASTEXITCODE -ne 0) {
        throw "Simulation for Architecture $arch (Patients: $numPatients, W: $windowSize) failed with exit code: $LASTEXITCODE"
    }

    if (-not (Test-Path $summaryFile)) {
        throw "Summary CSV file $summaryFile was not generated by Architecture $arch"
    }

    # Parse key-value metrics
    $metrics = @{}
    $lines = Get-Content $summaryFile
    foreach ($line in $lines | Select-Object -Skip 1) {
        $parts = $line.Split(',')
        if ($parts.Length -ge 2) {
            $metrics[$parts[0].Trim()] = $parts[1].Trim()
        }
    }
    return $metrics
}

